#!/usr/bin/env node

/**
 * 从 @rc-component/util 产物中提取 pickAttrs 的属性白名单。
 *
 * 为什么需要它：
 *   pickAttrs 的白名单决定了「哪些 props 会被透传到 DOM」，它是 DOM Contract 的一部分，
 *   必须逐字复刻。手抄 200+ 个属性名必然出错，所以从产物机器提取。
 *
 *   ⚠️ 提取的是【事实清单】，不是实现代码。实现由我们自己写（AGENTS.md H5/H6）。
 *
 * 用法：
 *   node scripts/extract-attr-allowlist.mjs                 # 自动下载 @rc-component/util@<版本>
 *   node scripts/extract-attr-allowlist.mjs --from <path>   # 用本地已解压的 es/pickAttrs.js
 *   RC_UTIL_VERSION=1.13.0 node scripts/...                 # 指定版本
 *
 * 产物：
 *   1. registry/source/rc-util-attr-allowlist.json   —— 事实清单（供审查与文档引用）
 *   2. packages/utils/src/pick-attrs-allowlist.ts    —— 可直接 import 的实现数据
 *      （之所以生成 TS 而不是让源码 import JSON：JSON 在 registry/ 下，跨包引用会破坏发布边界）
 *
 * 用法：
 *   node scripts/extract-attr-allowlist.mjs                 # 自动下载 @rc-component/util@<版本>
 *   node scripts/extract-attr-allowlist.mjs --from <path>   # 用本地已解压的 es/pickAttrs.js
 *   node scripts/extract-attr-allowlist.mjs --check         # 只校验产物是否与上游同步，不写文件
 *   RC_UTIL_VERSION=1.13.0 node scripts/...                 # 指定版本
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const VERSION = process.env.RC_UTIL_VERSION ?? '1.13.0';
const OUT = path.resolve('registry/source/rc-util-attr-allowlist.json');
const OUT_TS = path.resolve('packages/utils/src/pick-attrs-allowlist.ts');

function parseArgs() {
  const args = process.argv.slice(2);
  const i = args.indexOf('--from');
  return { from: i >= 0 ? args[i + 1] : null, check: args.includes('--check') };
}

/** 下载并解压 rc-util 到临时目录，返回 es/ 路径。 */
function fetchEs() {
  const cacheDir = path.join(os.tmpdir(), 'apollo-rc-util', VERSION);
  const esDir = path.join(cacheDir, 'package', 'es');
  if (fs.existsSync(path.join(esDir, 'pickAttrs.js'))) return esDir;

  fs.mkdirSync(cacheDir, { recursive: true });
  const tgz = path.join(cacheDir, 'util.tgz');
  const url = `https://registry.npmjs.org/@rc-component/util/-/util-${VERSION}.tgz`;
  console.log(`↓ ${url}`);
  execFileSync('curl', ['-fsSL', url, '-o', tgz], { stdio: 'inherit' });
  execFileSync('tar', ['-xzf', tgz, '-C', cacheDir], { stdio: 'inherit' });
  if (!fs.existsSync(esDir)) throw new Error(`解压后未找到 ${esDir}`);
  return esDir;
}

/**
 * 从 pickAttrs.js 里取出两个模板字面量：attributes / eventsName。
 * 用「模板字面量的起止反引号 + 变量名」定位，不依赖具体排版。
 */
function extractTemplate(src, varName) {
  const re = new RegExp(`const\\s+${varName}\\s*=\\s*\`([\\s\\S]*?)\``);
  const m = src.match(re);
  if (!m) throw new Error(`未找到模板字面量 const ${varName} = \`...\``);
  return m[1].split(/[\s\n]+/).filter(Boolean);
}

/** 找出最终 split 时拼接了哪些变量，确保我们没有漏掉第三块清单。 */
function extractPropListExpression(src) {
  const m = src.match(/const\s+propList\s*=\s*([^;]+);/);
  return m ? m[1].trim() : null;
}

const { from, check } = parseArgs();
const esDir = from ?? fetchEs();
const src = fs.readFileSync(path.join(esDir, 'pickAttrs.js'), 'utf8');

const attributes = extractTemplate(src, 'attributes');
const eventsName = extractTemplate(src, 'eventsName');
const propListExpr = extractPropListExpression(src);

// 断言：propList 只由这两个清单拼接而成，否则说明上游改结构了，必须人工复核。
// 只看模板插值 ${IDENT} —— 正则字面量里的字符会干扰标识符扫描，不参与判断。
const interpolated = propListExpr
  ? [...propListExpr.matchAll(/\$\{\s*([A-Za-z_$][\w$]*)\s*\}/g)].map((m) => m[1])
  : [];
const expected = ['attributes', 'eventsName'];
const unexpected = interpolated.filter((n) => !expected.includes(n));
const missing = expected.filter((n) => !interpolated.includes(n));
if (unexpected.length || missing.length) {
  console.error(`⚠️  propList 的模板插值不是预期的两个清单。`);
  console.error(`   实际插值：${interpolated.join(', ') || '(无)'}`);
  console.error(`   表达式：${propListExpr}`);
  console.error('   上游可能重构了 pickAttrs，请人工复核后再更新本清单。');
  process.exitCode = 1;
}

// 事件名与属性名的判定：React 合成事件名以 on + 大写字母开头。
const isEvent = (n) => /^on[A-Z]/.test(n);
const events = eventsName.filter(isEvent);
const nonEventInEvents = eventsName.filter((n) => !isEvent(n));
if (nonEventInEvents.length) {
  console.error(`⚠️  eventsName 中存在非事件名条目：${nonEventInEvents.join(', ')}`);
  process.exitCode = 1;
}

const json = {
  $comment:
    'GENERATED by scripts/extract-attr-allowlist.mjs. Do not hand-edit. ' +
    'pickAttrs 的透传白名单事实清单 —— DOM Contract 的一部分，实现必须逐字复刻。',
  source: `@rc-component/util@${VERSION}`,
  extractedFrom: path.join(esDir, 'pickAttrs.js'),
  propListExpression: propListExpr,
  counts: {
    attributes: attributes.length,
    events: events.length,
    total: attributes.length + events.length,
  },
  attributes,
  events,
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
const jsonText = `${JSON.stringify(json, null, 2)}\n`;
const tsText = renderTs(json);

if (check) {
  const problems = [];
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== jsonText)
    problems.push(path.relative(process.cwd(), OUT));
  if (!fs.existsSync(OUT_TS) || fs.readFileSync(OUT_TS, 'utf8') !== tsText)
    problems.push(path.relative(process.cwd(), OUT_TS));
  if (problems.length) {
    console.error('✗ 产物与上游 @rc-component/util 不同步，请重跑本脚本（去掉 --check）：');
    for (const p of problems) console.error(`   ${p}`);
    process.exit(1);
  }
  console.log('✓ pickAttrs 白名单产物与上游同步');
  process.exit(0);
}

fs.writeFileSync(OUT, jsonText);
fs.writeFileSync(OUT_TS, tsText);

console.log(`\n属性白名单：${attributes.length} 个`);
console.log(`事件白名单：${events.length} 个（全部需要经 event-name.ts 转换，详见该文件）`);
console.log(`→ ${OUT}`);
console.log(`→ ${OUT_TS}`);

/** 生成可被源码 import 的 TS 模块。 */
function renderTs(data) {
  const quote = (list) => list.map((n) => `  '${n}',`).join('\n');
  return `/**
 * ⚠️ 本文件由 \`scripts/extract-attr-allowlist.mjs\` 生成，**请勿手改**。
 *
 * 数据来源：${data.source} 的 \`pickAttrs\` 产物。
 *
 * 为什么必须是生成而不是手写：
 *   这 ${data.counts.total} 个名字决定了「哪些 props 会被透传到 DOM」，
 *   属于 DOM Contract 的一部分，必须逐字一致。手抄 200+ 个属性名必然出错。
 *
 * 同步校验：\`node scripts/extract-attr-allowlist.mjs --check\`（CI 会跑）。
 */

/** 属性白名单（${data.counts.attributes} 个）。 */
export const PICK_ATTRS_ATTRIBUTES: readonly string[] = [
${quote(data.attributes)}
];

/** 事件白名单（${data.counts.events} 个）。键名是 **React 合成事件名**，需经 event-name.ts 转换。 */
export const PICK_ATTRS_EVENTS: readonly string[] = [
${quote(data.events)}
];

/** 合并白名单。拼接顺序与上游的 propList 表达式一致：${data.propListExpression} */
export const PICK_ATTRS_ALL: ReadonlySet<string> = new Set([...PICK_ATTRS_ATTRIBUTES, ...PICK_ATTRS_EVENTS]);
`;
}
