#!/usr/bin/env node
/** Generate the current progress page from the audit state; historical reports stay immutable. */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { readAudit, summarizeAudit } from './audit-workflow.mjs';

const project = path.resolve(import.meta.dirname, '../..');
const sourceURL = 'https://github.com/apollocmh/apollo-design-ui/blob/master/';
const labels = {
  'zh-CN': {
    title: 'Vue 原生化：架构整改与最终验收',
    scope: '范围',
    architecture: '架构整改完成',
    historical: '历史完整交付',
    final: '本轮冻结验收通过',
    components: '组件单元',
    foundations: '基础包',
    task: '任务',
    state: '架构状态',
    owner: '当前负责人',
    evidence: '保留证据',
    statuses: {
      not_started: '未开始',
      partial: '已有专项，待续',
      in_progress: '进行中',
      done: '架构整改完成',
      blocked: '阻塞',
    },
  },
  'en-US': {
    title: 'Vue native architecture and final acceptance',
    scope: 'Scope',
    architecture: 'Architecture complete',
    historical: 'Historical deliveries',
    final: 'Passed on the frozen version',
    components: 'Component units',
    foundations: 'Foundation packages',
    task: 'Task',
    state: 'Architecture status',
    owner: 'Current owner',
    evidence: 'Retained evidence',
    statuses: {
      not_started: 'Not started',
      partial: 'Partial work retained',
      in_progress: 'In progress',
      done: 'Architecture complete',
      blocked: 'Blocked',
    },
  },
};
export function renderProgress(doc) {
  const summary = summarizeAudit(doc);
  const sections = Object.entries(labels).map(([locale, text]) => {
    const chinese = locale === 'zh-CN';
    const lead = chinese
      ? `当前阶段：**${doc.phase === 'architecture' ? '第一阶段：Vue 原生架构整改' : '第二阶段：冻结版本统一验收'}**。任务派发：**${doc.dispatch.status === 'paused' ? '暂停' : '进行中'}**；活动任务 ${summary.activeTasks.length}/${doc.dispatch.maxParallel}。`
      : `Current stage: **${doc.phase === 'architecture' ? 'Vue native architecture' : 'Frozen-version acceptance'}**. Dispatch: **${doc.dispatch.status}**; active tasks ${summary.activeTasks.length}/${doc.dispatch.maxParallel}.`;
    const table = [
      `| ${text.scope} | ${text.architecture} | ${text.historical} | ${text.final} |`,
      '| --- | --- | --- | --- |',
      ...[
        ['components', text.components],
        ['foundations', text.foundations],
      ].map(([key, name]) => {
        const row = summary[key];
        return `| ${name} | ${row.architectureDone}/${row.total} | ${row.historicalAccepted} | ${row.finalAccepted} |`;
      }),
    ];
    const note = chinese
      ? '历史交付沿用仍有效的代码、测试与证据，不代表已经对本轮冻结版本重新验证。第一阶段完成相关类型、核心行为及必要 Demo/消费者检查即可继续；非阻塞问题记录影响与延期理由，第二阶段统一执行九维验收。源码导入关系用于影响面分析，只有任务中明确登记的整改依赖才阻塞推进。'
      : 'Existing code, tests and valid evidence are retained. Historical deliveries do not claim a fresh frozen-version pass. Focused types, core behavior and necessary demo/consumer checks allow architecture work to progress. Record non-blocking issues and defer full nine-dimension acceptance to stage two. Imports describe impact; only explicit work dependencies block task completion.';
    const rows = doc.tasks.map((task) => {
      const evidence = [...new Set([...task.evidence, ...task.existingWork])];
      const link = evidence[0]
        ? `[${chinese ? '证据' : 'Evidence'}](${sourceURL}${evidence[0]})`
        : '—';
      return `| ${task.title} | ${text.statuses[task.architectureStatus]} | ${task.assignment?.owner ?? '—'} | ${link} |`;
    });
    return [
      `## ${locale}`,
      `## ${text.title}`,
      lead,
      table.join('\n'),
      note,
      chinese
        ? `全库最终验收：**${doc.finalAcceptance.status}**。未知、未测或延期均不计为通过。`
        : `Final library acceptance: **${doc.finalAcceptance.status}**. Unknown, untested and deferred checks are not passes.`,
      `| ${text.task} | ${text.state} | ${text.owner} | ${text.evidence} |\n| --- | --- | --- | --- |\n${rows.join('\n')}`,
      `[${chinese ? '历史进度与交付记录' : 'Historical progress and deliveries'}](${sourceURL}docs/history/audit-progress-2026-10-29.md)`,
    ].join('\n\n');
  });
  return `---\ntitle:\n  zh-CN: 整改进展\n  en-US: Audit Progress\norder: 0\n---\n\n<!-- Generated by registry/tools/audit-progress.mjs from registry/vue-native-audit.json. -->\n\n${sections.join('\n\n')}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try {
    const { values } = parseArgs({ options: { check: { type: 'boolean' } } });
    const file = path.join(project, 'packages/docs/content/guide/audit-progress.md');
    const next = renderProgress(readAudit(project));
    if (fs.readFileSync(file, 'utf8') !== next) {
      if (values.check) throw new Error('Progress view is stale; run pnpm registry:progress');
      fs.writeFileSync(file, next);
    }
    console.log('[audit-progress] current view matches the single audit state');
  } catch (error) {
    console.error(`[audit-progress] ${error.message}`);
    process.exitCode = 1;
  }
}
