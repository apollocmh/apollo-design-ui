import { execFileSync } from 'node:child_process';
import { cpSync, readFileSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';
import vue from '@vitejs/plugin-vue';
import { defineBuildConfig } from 'unbuild';
import sharedConfig from '../../scripts/unbuild-preserve-modules.mjs';

/** Reuse the foundation module layout; compile only this package's SFCs and declarations. */
export default defineBuildConfig({
  declaration: false,
  hooks: {
    'rollup:options'(ctx, options) {
      sharedConfig[0].hooks['rollup:options'](ctx, options);
      options.plugins.push(vue());
    },
    // Generate real declarations before unbuild validates package outputs, retaining failOnWarn.
    'rollup:done'(ctx) {
      const packageDir = ctx.options.rootDir;
      const temporary = resolve(packageDir, '.dts-tmp');
      rmSync(temporary, { recursive: true, force: true });
      try {
        execFileSync(
          process.execPath,
          [
            resolve(packageDir, '../../node_modules/vue-tsc/bin/vue-tsc.js'),
            '-p',
            'tsconfig.build.json',
            '--outDir',
            temporary,
          ],
          { cwd: packageDir, stdio: 'inherit' },
        );
        cpSync(resolve(temporary, 'packages/virtual-list/src'), resolve(packageDir, 'dist'), {
          recursive: true,
        });
      } finally {
        rmSync(temporary, { recursive: true, force: true });
      }
      const entry = readFileSync(resolve(packageDir, 'dist/index.d.ts'), 'utf8');
      if (!/\bexport\s+(type|interface|\{)/.test(entry)) {
        throw new Error('[virtual-list build] index.d.ts is not a generated declaration');
      }
      for (const name of ['VirtualList.vue.d.ts', 'Filler.vue.d.ts']) {
        const declaration = readFileSync(resolve(packageDir, 'dist', name), 'utf8');
        if (!/\bdeclare\s+(const|function)\b/.test(declaration)) {
          throw new Error(`[virtual-list build] ${name} is not a generated SFC declaration`);
        }
      }
      process.stdout.write('  ✔ VirtualList and Filler declarations generated by vue-tsc\n');
    },
  },
});
